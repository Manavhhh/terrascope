from typing import List, Optional
from app.models.schemas import DemoInvestigation, SurfaceChangeCategory, AnalysisRequest
from app.services.data_providers.sample_provider import SampleDataProvider
from app.services.engine.sar_processor import sar_processor

class DemoInvestigationService:
    def __init__(self):
        self.sample_provider = SampleDataProvider()
        self.investigations = self._build_investigations()

    def _build_investigations(self) -> List[DemoInvestigation]:
        catalog = self.sample_provider.catalog

        # Investigation A: 2023 Kahramanmaraş Turkey Earthquake & Fault Slip
        prod_a1 = catalog[0] # Turkey Pre
        prod_a2 = catalog[1] # Turkey Post
        req_a = AnalysisRequest(
            product_a_id=prod_a1.product_id,
            product_b_id=prod_a2.product_id,
            category=SurfaceChangeCategory.GROUND_DEFORMATION,
            algorithm="dinsar_phase_displacement",
            confidence_threshold=0.85
        )
        anl_a = sar_processor.run_analysis(req_a, prod_a1, prod_a2)

        inv_a = DemoInvestigation(
            investigation_id="INV-EARTHQUAKE-TURKEY",
            title="Kahramanmaraş M7.8 Rupture: InSAR Co-Seismic Fault Slip & Deformation",
            category=SurfaceChangeCategory.GROUND_DEFORMATION,
            location_name="East Anatolian Fault, Kahramanmaraş, Türkiye",
            coordinates=[36.92, 37.58, 450000.0],
            question="What is the magnitude, spatial extent, and asymmetry of crustal surface displacement along the East Anatolian Fault rupture?",
            data_source="Calibrated L-band InSAR Interferometric Pair (L2_GUNW Proxy)",
            observation_dates=[prod_a1.acquisition_date, prod_a2.acquisition_date],
            summary=(
                "Analysis of ascending L-band interferometric phase reveals severe sinistral strike-slip displacement across the "
                "East Anatolian Fault trace. Line-of-sight (LOS) motion reaches -42.4 cm (relative retreat) on the west flank and "
                "+38.6 cm (relative advance) on the east flank, spanning over 2,800 km²."
            ),
            methodology=(
                "Two geocoded single-look complex (SLC) SAR scenes were interferometrically combined, flattened using Copernicus 30m DEM, "
                "adaptive Goldstein phase filtered, and unwrapped using SNAPHU minimum-cost flow algorithm. Coherence threshold gamma >= 0.35."
            ),
            limitations=(
                "1D Line-of-Sight projection requires 3D decomposition with descending track for pure strike-slip vs dip-slip separation. "
                "Immediate fault gouge zone (<2km) suffers decorrelation."
            ),
            source_documentation_url="https://nisar.jpl.nasa.gov/mission/data-products/",
            product_a=prod_a1,
            product_b=prod_a2,
            precomputed_analysis=anl_a
        )

        # Investigation B: Assam Brahmaputra Monsoon Flood
        prod_b1 = catalog[2] # Assam Pre
        prod_b2 = catalog[3] # Assam Post
        req_b = AnalysisRequest(
            product_a_id=prod_b1.product_id,
            product_b_id=prod_b2.product_id,
            category=SurfaceChangeCategory.FLOOD_WETLAND,
            algorithm="log_ratio_backscatter",
            confidence_threshold=0.80
        )
        anl_b = sar_processor.run_analysis(req_b, prod_b1, prod_b2)

        inv_b = DemoInvestigation(
            investigation_id="INV-FLOOD-BRAHMAPUTRA",
            title="Brahmaputra Basin Severe Inundation: Radar Backscatter Specular Loss",
            category=SurfaceChangeCategory.FLOOD_WETLAND,
            location_name="Brahmaputra River Valley, Assam, India",
            coordinates=[92.8, 26.6, 550000.0],
            question="How much agricultural land and riparian wetland was inundated during peak monsoon flooding, penetrating seasonal cloud cover?",
            data_source="NISAR-ISRO Joint Coverage L-band GCOV (Geocoded Calibrated Backscatter)",
            observation_dates=[prod_b1.acquisition_date, prod_b2.acquisition_date],
            summary=(
                "Multi-temporal SAR backscatter ratio identifies 1,420 km² of inundated floodplain. "
                "Open water generates a steep -6.4 dB specular reflection loss, while flooded marshes exhibit "
                "+3.2 dB double-bounce enhancement."
            ),
            methodology=(
                "Terrain-flattened Gamma-0 radiometrically calibrated backscatter was speckle-filtered (Refined Lee 7x7). "
                "Log-ratio differencing was segmented using an automated bimodal Otsu thresholding method."
            ),
            limitations=(
                "Capillary waves generated by high surface winds can elevate open water backscatter, occasionally underestimating flood extent. "
                "Dense closed forest canopies attenuate L-band signal."
            ),
            source_documentation_url="https://bhoonidhi.nrsc.gov.in",
            product_a=prod_b1,
            product_b=prod_b2,
            precomputed_analysis=anl_b
        )

        # Investigation C: California Central Valley Agricultural Phenology & Subsidence
        prod_c1 = catalog[4] # Valley Early
        prod_c2 = catalog[5] # Valley Peak
        req_c = AnalysisRequest(
            product_a_id=prod_c1.product_id,
            product_b_id=prod_c2.product_id,
            category=SurfaceChangeCategory.AGRICULTURE,
            algorithm="dual_pol_rvi_delta",
            confidence_threshold=0.75
        )
        anl_c = sar_processor.run_analysis(req_c, prod_c1, prod_c2)

        inv_c = DemoInvestigation(
            investigation_id="INV-AGRI-CENTRAL-VALLEY",
            title="San Joaquin Valley Agro-Ecosystem: Polarimetric RVI Phenology & Canopy Biomass",
            category=SurfaceChangeCategory.AGRICULTURE,
            location_name="San Joaquin Valley, California, USA",
            coordinates=[-119.8, 36.6, 420000.0],
            question="Can quad-polarimetric L-band radar track crop canopy expansion and distinguish volumetric scattering from bare agricultural soil?",
            data_source="NISAR L-SAR Full Polarimetric (QUAD) L2_GCOV Science Demonstration",
            observation_dates=[prod_c1.acquisition_date, prod_c2.acquisition_date],
            summary=(
                "Quad-polarimetric decomposition tracks rapid crop canopy closure across 980 km² of farmland. "
                "Radar Vegetation Index (RVI) increases by +0.38, driven by dominant HV volume scattering within orchard and row crops."
            ),
            methodology=(
                "Calculated Radar Vegetation Index RVI = 4*HV / (HH + HV) across pre- and peak-season observations, "
                "supported by Freeman-Durden 3-component polarimetric decomposition."
            ),
            limitations=(
                "Significant topsoil dielectric moisture fluctuations immediately following irrigation events can bias the HH co-polarized return. "
                "Crop row azimuth alignment creates anisotropic returns."
            ),
            source_documentation_url="https://nisar.jpl.nasa.gov/mission/data-products/",
            product_a=prod_c1,
            product_b=prod_c2,
            precomputed_analysis=anl_c
        )

        return [inv_a, inv_b, inv_c]

    def get_all(self) -> List[DemoInvestigation]:
        return self.investigations

    def get_by_id(self, inv_id: str) -> Optional[DemoInvestigation]:
        for inv in self.investigations:
            if inv.investigation_id == inv_id:
                return inv
        return None

demo_service = DemoInvestigationService()
